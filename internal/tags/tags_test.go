func TestPath(t *testing.T) {
	cases := map[string]string{
		"/r/20261013/rec-reduce-transcript.txt": "/r/20261013/rec-reduce-tags.yml",
		"/r/20261013/rec-reduce.mp3":            "/r/20261013/rec-reduce-tags.yml",
		"notes.txt":                             "notes-tags.yml",
	}
	for in, want := range cases {
		if got := Path(in); got != want {
			t.Errorf("Path(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestDateFromName(t *testing.T) {
	cases := map[string]string{
		"/x/vokoscreenNG-2026-10-13_14-09-55-reduce-transcript.txt": "2026-10-13",
		"/records/20261013/meeting-20240313-transcript.txt":         "2024-03-13",
		"meeting-transcript.txt":                                    "",
		"call-123456789-transcript.txt":                             "",
		// Google Meet downloads write the date with underscores.
		"/r/20261015/the-ming-disco-2026_10_15-15_00-CEST-Recording-reduce-transcript.txt": "2026-10-15",
		// No date in the name: the records/<YYYYMMDD>/ folder gives it.
		"/records/20261015/standup-transcript.txt": "2026-10-15",
		"/records/notes/standup-transcript.txt":    "",
	}
	for in, want := range cases {
		if got := DateFromName(in); got != want {
			t.Errorf("DateFromName(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestParseToleratesFencesAndNormalizes(t *testing.T) {
	answer := "Here you go:\n```json\n" + `{
  "type": "Standup",
  "summary": "  Weekly   sync on\ntokens ",
  "topics": ["Design Tokens", "design-tokens", "Dark mode!", ""],
  "people": [" Alan ", "alan", "Marie  Curie"],
  "tickets": ["liv-17445", "not a ticket", "LIV-17445"],
  "projects": ["Cockpit"]
}` + "\n```"

	got, err := Parse(answer)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if got.Type != "standup" {
		t.Errorf("type = %q", got.Type)
	}
	if got.Summary != "Weekly sync on tokens" {
		t.Errorf("summary = %q", got.Summary)
	}
	check := func(field string, got []string, want string) {
		if strings.Join(got, ",") != want {
			t.Errorf("%s = %v, want %s", field, got, want)
		}
	}
	check("topics", got.Topics, "dark-mode,design-tokens")
	check("people", got.People, "Alan,Marie Curie")
	check("tickets", got.Tickets, "LIV-17445")
	check("projects", got.Projects, "cockpit")
}

func TestParseUnknownTypeAndErrors(t *testing.T) {
	got, err := Parse(`{"type": "brainstorm", "summary": "s", "topics": ["a"]}`)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if got.Type != "other" {
		t.Errorf("type = %q, want other", got.Type)
	}
	if got.People == nil || got.Tickets == nil {
		t.Error("missing lists should become empty, not nil")
	}

	for _, bad := range []string{"no json here", `{"topics": [1, 2]}`} {
		if _, err := Parse(bad); err == nil {
			t.Errorf("Parse(%q) should fail", bad)
		}
	}
}

func TestWriteAndCollectVocabulary(t *testing.T) {
	root := t.TempDir()
	write := func(rel string, tg Tags) {
		t.Helper()
		path := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			t.Fatal(err)
		}
		if err := Write(path, Normalize(tg)); err != nil {
			t.Fatalf("Write: %v", err)
		}
	}
	write("20261001/a-tags.yml", Tags{Topics: []string{"dark-mode", "design-tokens"}, Projects: []string{"cockpit"}})
	write("20261002/b-tags.yml", Tags{Topics: []string{"design-tokens"}})
	write("c-tags.yml", Tags{Topics: []string{"hiring"}})
	// Two levels deep: outside the bounded scan.
	write("20261003/sub/d-tags.yml", Tags{Topics: []string{"too-deep"}})

	data, _ := os.ReadFile(filepath.Join(root, "20261001/a-tags.yml"))
	text := string(data)
	for _, want := range []string{"# Generated by goscribe", "topics:\n    - dark-mode\n    - design-tokens\n", "people: []"} {
		if !strings.Contains(text, want) {
			t.Errorf("tags file missing %q:\n%s", want, text)
		}
	}

	v := CollectVocabulary(root)
	if strings.Join(v.Topics, ",") != "design-tokens,dark-mode,hiring" {
		t.Errorf("topics = %v, want most used first and no deep files", v.Topics)
	}
	if strings.Join(v.Projects, ",") != "cockpit" {
		t.Errorf("projects = %v", v.Projects)
	}
}

func TestPromptIncludesVocabulary(t *testing.T) {
	p := Prompt(Vocabulary{Topics: []string{"design-tokens", "hiring"}, Projects: []string{"cockpit"}})
	for _, want := range []string{"design-tokens, hiring", "cockpit", "JSON object", "standup"} {
		if !strings.Contains(p, want) {
			t.Errorf("prompt missing %q", want)
		}
	}
	if strings.Contains(Prompt(Vocabulary{}), "Reuse these") {
		t.Error("empty vocabulary should not add reuse lines")
	}
}
